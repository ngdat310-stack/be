-- The guest says "I have transferred": such an order is never cancelled for not being paid, the cashier checks it
alter table orders add column transfer_claimed_at timestamp(6);

-- Browser push subscriptions of a web takeaway guest (no account: the order's tracking link is the key)
create table push_subscriptions (
    id         integer generated by default as identity primary key,
    order_id   integer not null references orders (id) on delete cascade,
    endpoint   varchar(1000) not null,
    p256dh     varchar(200) not null,
    auth       varchar(100) not null,
    created_at timestamp(6) not null default now(),
    unique (order_id, endpoint)
);
